static const char MSG[] = "MKSTOOR stage-4 test payload: kernel image bytes...";

static void hex_eq(const u8 *d, const char *want)
{
        char got[65];
        static const char H[] = "0123456789abcdef";
        for (int i = 0; i < 32; i++) {
                got[2 * i] = H[d[i] >> 4];
                got[2 * i + 1] = H[d[i] & 0xf];
        }
        got[64] = 0;
        CHECK(strcmp(got, want) == 0);
}

int main(void)
{
        u8 dig[32];

        /* FIPS 180-4 / NIST short vectors */
        mks_sha256_buf("abc", 3, dig);
        hex_eq(dig, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");

        mks_sha256_buf("", 0, dig);
        hex_eq(dig, "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");

        const char *long56 = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
        mks_sha256_buf(long56, strlen(long56), dig);
        hex_eq(dig, "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1");

        /* streaming API must agree with one-shot over a multi-block input */
        char million[1000000];
        memset(million, 'a', sizeof(million));
        struct mks_sha256_ctx ctx;
        mks_sha256_init(&ctx);
        for (size_t off = 0; off < sizeof(million); off += 9973) {
                size_t n = 9973;
                if (off + n > sizeof(million))
                        n = sizeof(million) - off;
                mks_sha256_update(&ctx, million + off, n);
        }
        mks_sha256_final(&ctx, dig);
        hex_eq(dig, "cdc76e5c9914fb9281a1c7e284d73e67f1809a44a5042f110554413847282290");

        /* RSA-SHA256 PKCS#1 v1.5 verify against the OpenSSL test vector */
        CHECK(mks_rsa_sha256_verify(MSG, sizeof(MSG) - 1, TEST_SIG,
                                    sizeof(TEST_SIG), TEST_N, sizeof(TEST_N),
                                    TEST_E, sizeof(TEST_E)) == MKSTOOR_OK);

        /* tampered signature must be rejected as SECURITY */
        CHECK(mks_rsa_sha256_verify(MSG, sizeof(MSG) - 1, TEST_SIG_BAD,
                                    sizeof(TEST_SIG_BAD), TEST_N,
                                    sizeof(TEST_N), TEST_E,
                                    sizeof(TEST_E)) == MKSTOOR_ERR_SECURITY);

        /* wrong message must be rejected */
        CHECK(mks_rsa_sha256_verify("different", 9, TEST_SIG, sizeof(TEST_SIG),
                                    TEST_N, sizeof(TEST_N), TEST_E,
                                    sizeof(TEST_E)) == MKSTOOR_ERR_SECURITY);

        /* malformed args */
        CHECK(mks_rsa_sha256_verify(NULL, 0, TEST_SIG, 128, TEST_N, 128,
                                    TEST_E, 3) == MKSTOOR_ERR_INVALID_ARG);
        CHECK(mks_rsa_sha256_verify(MSG, 8, TEST_SIG, 100, TEST_N, 128,
                                    TEST_E, 3) == MKSTOOR_ERR_UNSUPPORTED);

        return TEST_SUMMARY();
}
