def pack(art: str) -> list[int]:
    rows = [ln.strip() for ln in art.splitlines() if ln.strip()]
    assert len(rows) <= H, f"too many rows: {rows}"
    for r in rows:
        assert len(r) <= W, f"row too wide ({len(r)}): {r!r}"
        assert set(r) <= {".", "#"}, f"bad chars: {r!r}"
    cols = [0] * W
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == "#":
                cols[x] |= 1 << y
    return cols


def main() -> int:
    first, last = 0x20, 0x7E
    out = sys.stdout
    out.write("/* SPDX-License-Identifier: AGPL-3.0-only */\n")
    out.write("/* MKSTOOR — generated by tools/gen_font.py; do not edit by hand.\n *\n")
    out.write(" * Built-in 6x8 bitmap font covering printable ASCII (0x20..0x7E).\n")
    out.write(" * Column-major glyphs: bits[6*idx + col], LSB of each byte = top row.\n")
    out.write(" */\n")
    out.write("#include <mkstoor/types.h>\n\n")
    out.write(f"#define MKS_FONT_GLYPH_COUNT {last - first + 1}\n\n")
    out.write("const u8 mks_font_builtin_bits[MKS_FONT_GLYPH_COUNT][6] = {\n")
    missing = []
    for cp in range(first, last + 1):
        c = chr(cp)
        art = GLYPHS.get(c)
        if art is None:
            missing.append(c)
            art = GLYPHS[' ']
        cols = pack(art)
        body = ", ".join(f"0x{v:02x}" for v in cols)
        out.write(f"    {{ {body} }},  /* {cp:#04x} '{c}' */\n")
    out.write("};\n")
    if missing:
        print(f"warning: defaulted glyphs: {missing}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
